// ─────────────────────────────────────────────────────────────────────────────

/// Prove that a `ServiceCodegen`-generated server stub composes with
/// `NativeHealthService` inside a `NativeServiceRegistry`.
///
/// Uses the `compile_link.rs` pattern:
/// 1. Write a tiny proto to temp dir.
/// 2. Builder::compile() → generate `.services.rs` stubs.
/// 3. Synthesise a crate that registers both services in a registry.
/// 4. Run `cargo check`; assert exit code 0.
#[test]
#[ignore]
fn generated_service_composes_with_health_registry() {
    // 1. Create a temp dir and write the proto.
    let temp_dir = make_temp_dir("health_compose");
    let proto_file = temp_dir.join("healthinteg.proto");
    fs::write(&proto_file, HEALTH_INTEG_PROTO).expect("write proto file");

    // 2. Compile the proto via Builder — generates stubs into temp_dir.
    let build_result = oxirpc_build::Builder::new()
        .build_client(true)
        .build_server(true)
        .out_dir(&temp_dir)
        .compile(&[&proto_file], &[&temp_dir]);

    assert!(
        build_result.is_ok(),
        "Builder::compile() must succeed; got: {:?}",
        build_result.err()
    );

    // 3. Read the generated service stubs.
    let services_file = temp_dir.join("healthinteg.services.rs");
    assert!(
        services_file.exists(),
        "expected healthinteg.services.rs in {temp_dir:?}"
    );
    let service_code = fs::read_to_string(&services_file).expect("read healthinteg.services.rs");

    // Sanity: both server and client modules are present.
    assert!(
        service_code.contains("pub mod ping_service_server"),
        "native codegen must emit ping_service_server"
    );
    assert!(
        service_code.contains("pub mod ping_service_client"),
        "native codegen must emit ping_service_client"
    );

    // 4. Run cargo check on the synthesised crate.
    run_cargo_check(&temp_dir, &service_code);
}

#![forbid(unsafe_code)]
#![warn(missing_docs)]
//! Build-time proto compiler for OxiRPC — no `protoc` required.
//!
//! Uses `oxiproto-build` (which delegates to `protox`, a pure-Rust `.proto`
//! parser) to parse and resolve `.proto` files without spawning `protoc`.
//!
//! # Default codegen path (native `ServiceCodegen`)
//!
//! `Builder::compile()` now routes through [`codegen::ServiceCodegen`] by
//! default.  This emits **service stub modules** (`*_server` / `*_client`)
//! for every service declared in the `.proto` files.
//!
//! **Important:** the native path emits service stubs only — it does **not**
//! generate prost message types.  Downstream `build.rs` users that need
//! message type generation should either:
//!
//! 1. Run `prost_build` (or `tonic_prost_build`) separately for message types,
//!    then use `Builder::compile()` for service stubs.
//! 2. Enable the `legacy-tonic-codegen` feature (see below) to restore the
//!    previous all-in-one code generation via `tonic-prost-build`.
//!
//! # Legacy path (`tonic-prost-build`)
//!
//! Opt in with `features = ["legacy-tonic-codegen"]` in your
//! `[build-dependencies]`.  When active, `Builder::compile()` delegates to
//! `tonic_prost_build::compile_fds`, which generates both prost message types
//! and service stubs in a single pass.  All `Builder::type_attribute`,
//! `field_attribute`, `btree_map`, `bytes`, `extern_path`, and
//! `compile_well_known_types` settings apply exclusively to this path.
//!
//! # Example (`build.rs`) — default native path
//!
//! ```rust,ignore
//! fn main() -> Result<(), Box<dyn std::error::Error>> {
//!     oxirpc_build::compile_protos(&["proto/greeter.proto"], &["proto/"])?;
//!     Ok(())
//! }
//! ```
//!
//! # Example (`build.rs`) — legacy path (Cargo.toml: `features = ["legacy-tonic-codegen"]`)
//!
//! ```rust,ignore
//! fn main() -> Result<(), Box<dyn std::error::Error>> {
//!     // Both message types and service stubs generated by tonic-prost-build.
//!     oxirpc_build::compile_protos(&["proto/greeter.proto"], &["proto/"])?;
//!     Ok(())
//! }
//! ```


/// Inspect a `FileDescriptorSet` for common proto structure problems.
///
/// Returns a list of human-readable warning strings.  These are non-fatal —
/// compilation already succeeded at this point.
///
/// Currently checks:
/// - Files without a `package` declaration.
/// - Imports of `google/protobuf/*.proto` when nothing in the file references
///   the `google.protobuf.*` namespace (likely unused import).
fn validate_imports(fds: &prost_types::FileDescriptorSet) -> Vec<String> {
    let mut warnings = Vec::new();

    for file in &fds.file {
        let file_name = file.name().to_owned();

        // --- missing package declaration ---
        if file.package().is_empty() && !file_name.is_empty() {
            warnings.push(format!(
                "{file_name}: no package declaration \
                 (consider adding 'package your.package;')"
            ));
        }

        // --- potentially unused google.protobuf.* imports ---
        for dep in &file.dependency {
            if !dep.starts_with("google/protobuf/") {
                continue;
            }

            // Check whether any field, message extension, or service method
            // references the "google.protobuf." prefix.
            let referenced = file_references_google_protobuf(file);
            if !referenced {
                warnings.push(format!(
                    "{file_name}: imports '{dep}' but no types from \
                     'google.protobuf.*' are referenced \
                     (possibly unused import)"
                ));
            }
        }
    }

    warnings
}

/// Returns `true` if any field, extension, or method in `file` references a
/// type whose name starts with `google.protobuf.`.
fn file_references_google_protobuf(file: &prost_types::FileDescriptorProto) -> bool {
    const PREFIX: &str = ".google.protobuf.";

    // Check message fields and nested messages (one level deep is enough for
    // the heuristic).
    for msg in &file.message_type {
        for field in &msg.field {
            if field.type_name().starts_with(PREFIX) {
                return true;
            }
            if field.extendee().starts_with(PREFIX) {
                return true;
            }
        }
        for ext in &msg.extension {
            if ext.type_name().starts_with(PREFIX) || ext.extendee().starts_with(PREFIX) {
                return true;
            }
        }
    }

    // Top-level extensions
    for ext in &file.extension {
        if ext.type_name().starts_with(PREFIX) || ext.extendee().starts_with(PREFIX) {
            return true;
        }
    }

    // Service method input/output types
    for svc in &file.service {
        for method in &svc.method {
            if method.input_type().starts_with(PREFIX) || method.output_type().starts_with(PREFIX) {
                return true;
            }
        }
    }

    false
}


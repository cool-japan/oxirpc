/// Errors produced during build-time proto compilation.
#[derive(Debug)]
pub enum OxiRpcBuildError {
    /// A protobuf schema error, with optional source location.
    Proto {
        /// Source file path (if available).
        path: Option<String>,
        /// Line number (1-indexed, if available).
        line: Option<u32>,
        /// Column number (1-indexed, if available).
        col: Option<u32>,
        /// Human-readable error message.
        msg: String,
    },
    /// Code generation error.
    Codegen(String),
    /// I/O failure.
    Io(std::io::Error),
}

impl std::fmt::Display for OxiRpcBuildError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            OxiRpcBuildError::Proto {
                path,
                line,
                col,
                msg,
            } => match (path, line, col) {
                (Some(p), Some(l), Some(c)) => write!(f, "{p}:{l}:{c}: {msg}"),
                (Some(p), Some(l), None) => write!(f, "{p}:{l}: {msg}"),
                (Some(p), None, _) => write!(f, "{p}: {msg}"),
                _ => write!(f, "proto parse error: {msg}"),
            },
            OxiRpcBuildError::Codegen(s) => write!(f, "codegen error: {s}"),
            OxiRpcBuildError::Io(e) => write!(f, "I/O error: {e}"),
        }
    }
}

impl std::error::Error for OxiRpcBuildError {}

impl From<std::io::Error> for OxiRpcBuildError {
    fn from(e: std::io::Error) -> Self {
        OxiRpcBuildError::Io(e)
    }
}
// ---------------------------------------------------------------------------
// oxiproto_core::OxiProtoError → OxiRpcBuildError conversion
// ---------------------------------------------------------------------------

/// Convert an [`oxiproto_core::OxiProtoError`] to [`OxiRpcBuildError`].
///
/// Parse errors are mapped to [`OxiRpcBuildError::Proto`] with structured
/// location info extracted from the `"file:line:col: message"` pattern.
/// I/O errors become [`OxiRpcBuildError::Io`]; codegen errors become
/// [`OxiRpcBuildError::Codegen`].
fn from_oxiproto_error(e: oxiproto_core::OxiProtoError) -> OxiRpcBuildError {
    match e {
        oxiproto_core::OxiProtoError::ParseError(ref msg) => {
            // Attempt to parse "file:line:col: message" prefix so we can
            // populate the structured Proto variant with location info.
            parse_proto_error_string(msg)
        }
        oxiproto_core::OxiProtoError::IoError(io_err) => OxiRpcBuildError::Io(io_err),
        oxiproto_core::OxiProtoError::CodegenError(msg) => OxiRpcBuildError::Codegen(msg),
        other => OxiRpcBuildError::Codegen(other.to_string()),
    }
}

/// Parse a `"file:line:col: message"` or `"file:line: message"` string into an
/// [`OxiRpcBuildError::Proto`] with structured location information.
///
/// Falls back to `Proto { path: None, line: None, col: None, msg }` when the
/// prefix is absent or malformed.
fn parse_proto_error_string(msg: &str) -> OxiRpcBuildError {
    // Strategy: split on ':' and try to read u32 segments at positions 1 and 2.
    // We must handle Windows drive letters like "C:\path\file.proto:3:5: …"
    // by skipping single-char segments as likely drive letters.
    let parts: Vec<&str> = msg.splitn(5, ':').collect();

    if parts.len() >= 3 {
        // Handle Windows drive letter prefix: if parts[0] is a single ASCII
        // alpha char, the "file" part is parts[0] + ":" + parts[1].
        let (file_raw, line_idx, col_idx) = if parts[0].len() == 1
            && parts[0]
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_alphabetic())
        {
            if parts.len() >= 5 {
                let file = format!("{}:{}", parts[0], parts[1]);
                (Some(file), 2usize, 3usize)
            } else {
                return OxiRpcBuildError::Proto {
                    path: None,
                    line: None,
                    col: None,
                    msg: msg.to_owned(),
                };
            }
        } else {
            (Some(parts[0].to_owned()), 1usize, 2usize)
        };

        if let Ok(line) = parts[line_idx].trim().parse::<u32>() {
            if let Ok(col) = parts[col_idx].trim().parse::<u32>() {
                let message = parts[(col_idx + 1)..]
                    .join(":")
                    .trim_start_matches(' ')
                    .to_owned();
                return OxiRpcBuildError::Proto {
                    path: file_raw,
                    line: Some(line),
                    col: Some(col),
                    msg: if message.is_empty() {
                        msg.to_owned()
                    } else {
                        message
                    },
                };
            }
            let message = parts[(line_idx + 1)..]
                .join(":")
                .trim_start_matches(' ')
                .to_owned();
            return OxiRpcBuildError::Proto {
                path: file_raw,
                line: Some(line),
                col: None,
                msg: if message.is_empty() {
                    msg.to_owned()
                } else {
                    message
                },
            };
        }
    }

    OxiRpcBuildError::Proto {
        path: None,
        line: None,
        col: None,
        msg: msg.to_owned(),
    }
}

